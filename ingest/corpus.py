"""The corpus: one pinned 10-K per company, stored in `ingest/corpus.toml`.

Filings are pinned by accession number so the corpus (and the eval golden set built on it)
never drifts when companies publish new reports. Re-pin deliberately with:

    python -m ingest.corpus resolve
"""

from __future__ import annotations

import argparse
import asyncio
import tomllib
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from common.config import get_settings
from ingest.edgar import ARCHIVE_URL, EdgarClient

CORPUS_PATH = Path(__file__).parent / "corpus.toml"

# (ticker, CIK, display name). CIKs are pinned explicitly: tickers can move between legal
# entities (e.g. XOM now maps to "ExxonMobil Holdings Corp", which has no 10-K yet).
